@router.post("/muster/{crew_id}/safe")
@router.put("/emergency/muster/{crew_id}/safe")
async def mark_safe(crew_id: str, current_user: dict = Depends(require_permission("ACK_INCIDENT"))):
    col = get_muster_col()
    await col.update_one({"$or": [{"personnel_id": crew_id}, {"crew_id": crew_id}]}, {"$set": {"status": "SAFE", "updated_at": datetime.utcnow()}})
    await log_action(str(current_user["_id"]), current_user["role"], "MARK_SAFE", crew_id, "SUCCESS")
    return base_response({"status": "safe"})

